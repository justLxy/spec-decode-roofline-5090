"""Export the main results as Markdown tables (no GPU needed).

Reads the committed summaries in results/summary/ and writes docs/results_tables.md.
Run from anywhere:  python scripts/export_tables.py
Uses only pandas and the standard library, and the output is deterministic.
"""

import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
SUMMARY = ROOT / "results" / "summary"
OUT = ROOT / "docs" / "results_tables.md"

CONTEXTS = ["specbench", "ctx512", "ctx2k"]
FIXED_K = [f"k{k}" for k in range(1, 6)]
MISSING = "–"


def fmt(x, nd=2):
    """Format a number with nd decimals, or a dash if it is missing."""
    return MISSING if x is None or pd.isna(x) else f"{x:.{nd}f}"


def md_table(headers, rows, align):
    """Render a Markdown table; align is one of 'l' or 'r' per column."""
    sep = [":---" if a == "l" else "---:" for a in align]
    lines = ["| " + " | ".join(headers) + " |", "| " + " | ".join(sep) + " |"]
    lines += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(lines)


def best_k_table(context):
    """Table 1 for one context: no-SD vs. the best fixed K and doc_table, per concurrency."""
    df = pd.read_csv(SUMMARY / f"e2_{context}.csv")
    # Some files also carry the no-SD rows of the other context, so filter on the column too.
    df = df[df["context"] == context]
    rows = []
    for conc, g in df.groupby("concurrency", sort=True):
        by = g.set_index("setting")
        if "nosd" not in by.index:
            continue
        nosd = by.at["nosd", "mean_tpot_ms"]
        ks = by.loc[by.index.intersection(FIXED_K)].dropna(subset=["mean_tpot_ms"])
        if ks.empty:
            best, tpot, ci, speedup = MISSING, None, MISSING, MISSING
        else:
            best = ks["mean_tpot_ms"].idxmin()
            tpot = ks.at[best, "mean_tpot_ms"]
            ci = f"[{fmt(ks.at[best, 'mean_tpot_ms_lo'])}, {fmt(ks.at[best, 'mean_tpot_ms_hi'])}]"
            speedup = f"{nosd / tpot:.2f}×"
        doc = by.at["doc_table", "mean_tpot_ms"] if "doc_table" in by.index else None
        rows.append([int(conc), fmt(nosd), best.upper() if best != MISSING else best, fmt(tpot), ci,
                     speedup, fmt(doc)])
    headers = ["Concurrency", "No-SD TPOT (ms)", "Best K", "Best TPOT (ms)", "95% CI (ms)",
               "Speedup (No-SD / best)", "doc_table TPOT (ms)"]
    return md_table(headers, rows, ["r", "r", "l", "r", "r", "r", "r"])


def goodput_table():
    """Table 2: goodput, SLO attainment and TPOT percentiles per policy, plus the SLO line."""
    data = json.loads((SUMMARY / "e7_goodput_main.json").read_text())
    rows = []
    for name, p in data["policies"].items():
        lo, hi = p["ci"]
        rows.append([f"`{name}`", fmt(p["goodput_rps"]), f"[{fmt(lo)}, {fmt(hi)}]",
                     fmt(100 * p["slo_attainment"], 1), fmt(p["tpot_p50_ms"]), fmt(p["tpot_p99_ms"])])
    headers = ["Policy", "Goodput (req/s)", "95% CI (req/s)", "SLO attainment (%)",
               "p50 TPOT (ms)", "p99 TPOT (ms)"]
    table = md_table(headers, rows, ["l", "r", "r", "r", "r", "r"])
    slo = data["slo"]
    seeds = ", ".join(str(s) for s in data["seeds"])
    note = (f"SLO: TTFT ≤ {slo['ttft_ms']} ms and TPOT ≤ {slo['tpot_ms']} ms per request "
            f"(a request counts toward goodput only if it meets both). Seeds: {seeds}.")
    return table + "\n\n" + note


def main():
    parts = [
        "<!-- Generated by scripts/export_tables.py from results/summary/. Do not edit by hand. -->",
        "",
        "# Results tables",
        "",
        "## Table 1: Best fixed K vs. no-SD (E2, mean TPOT)",
        "",
        ("Best K is the setting among K1–K5 with the lowest mean TPOT at that concurrency. "
         "A dash means that setting was not run there."),
    ]
    for context in CONTEXTS:
        parts += ["", f"### `{context}`", "", best_k_table(context)]
    parts += ["", "## Table 2: Goodput per policy (E7, main run)", "", goodput_table(), ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(parts), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
